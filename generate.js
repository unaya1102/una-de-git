/* ===== 2) 谚文 → 罗马音 转换器（Revised Romanization 近似）===== */
const CHO=['g','kk','n','d','tt','r','m','b','pp','s','ss','','j','jj','ch','k','t','p','h'];
const JUNG=['a','ae','ya','yae','eo','e','yeo','ye','o','wa','wae','oe','yo','u','wo','we','wi','yu','eu','ui','i'];
const JONG=['','k','k','ks','n','nj','nh','t','l','lk','lm','lb','ls','lt','lp','lh','m','p','ps','t','t','ng','t','t','k','t','p','t'];
function romanizeSyllable(ch){
  const code=ch.charCodeAt(0)-0xAC00;
  if(code<0||code>11171) return ch;
  const cho=Math.floor(code/588), jung=Math.floor((code%588)/28), jong=code%28;
  return CHO[cho]+JUNG[jung]+JONG[jong];
}
function romanize(str){ return [...str].map(romanizeSyllable).join(''); }

