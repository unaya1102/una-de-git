function buildWord([hanja, mean, tag]){
  const chars=[];
  let hangul='';
  for(const ch of hanja){
    const e=H[ch];
    if(!e){ throw new Error('缺少汉字映射: '+ch+' (词: '+hanja+')'); }
    const k=e[0].split('/')[0];
    hangul+=k;
    chars.push({h:ch,k:k,m:e[1]});
  }
  return {hanja, hangul, roman:romanize(hangul), mean, tags:[tag], chars};
}

